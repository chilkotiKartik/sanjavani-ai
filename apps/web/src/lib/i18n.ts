/**
 * A language may be missing keys; English is the floor. Mirrors `pick` in
 * medical-safety, deliberately — one fallback rule for the whole product.
 */
const dictionaries: Partial<Record<Language, Partial<Record<MessageKey, string>>>> = { en, hi, hinglish, bn };

/** Share of the interface written in this language, 0–1. Used to disclose fallback. */
export function languageCoverage(language: Language): number {
  const dict = dictionaries[language];
  if (!dict) return 0;
  const keys = Object.keys(en) as MessageKey[];
  return keys.filter((k) => dict[k] !== undefined).length / keys.length;
}

export function translate(language: Language, key: MessageKey, vars?: Record<string, string | number>): string {
  const template = dictionaries[language]?.[key] ?? en[key];
  return vars ? template.replace(/\{(\w+)\}/g, (_, k: string) => String(vars[k] ?? '')) : template;
}

